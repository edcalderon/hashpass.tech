#!/usr/bin/env node
// Regenerates src/generated-templates.ts from templates/**/*.html and
// assets/* so email content ships as plain importable TS source instead of
// files renderer.ts read from disk at runtime via fs.readFileSync. That
// runtime approach depended on packages/emails/templates and .../assets
// existing on disk relative to a guessed __dirname inside the deployed
// Lambda bundle -- confirmed broken in production (ENOENT: no such file or
// directory) because the Expo Router API Lambda's bundling process only
// includes JS/TS module content, not arbitrary sibling directories of
// static files. Inlining as string constants sidesteps that entirely: any
// bundler that can bundle this package's .ts source at all necessarily
// includes these too.
//
// Run manually after editing a template or asset:
//   node packages/emails/scripts/generate-templates.mjs
// (Also runs automatically as part of `pnpm run build` in this package.)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(__dirname, '..');
const TEMPLATES_DIR = path.join(PACKAGE_ROOT, 'templates');
const ASSETS_DIR = path.join(PACKAGE_ROOT, 'assets');
const OUTPUT_PATH = path.join(PACKAGE_ROOT, 'src', 'generated-templates.ts');

const ASSET_MIME_TYPES = {
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp',
};

function readTemplates() {
  const templates = {};
  for (const templateName of fs.readdirSync(TEMPLATES_DIR).sort()) {
    const templateDir = path.join(TEMPLATES_DIR, templateName);
    if (!fs.statSync(templateDir).isDirectory()) continue;
    templates[templateName] = {};
    for (const file of fs.readdirSync(templateDir).sort()) {
      if (!file.endsWith('.html')) continue;
      const locale = file.replace(/\.html$/, '');
      templates[templateName][locale] = fs.readFileSync(path.join(templateDir, file), 'utf-8');
    }
  }
  return templates;
}

function readAssetsAsDataUris() {
  const assets = {};
  for (const file of fs.readdirSync(ASSETS_DIR).sort()) {
    const ext = path.extname(file).toLowerCase();
    const mimeType = ASSET_MIME_TYPES[ext];
    if (!mimeType) continue;
    const buffer = fs.readFileSync(path.join(ASSETS_DIR, file));
    assets[file] = `data:${mimeType};base64,${buffer.toString('base64')}`;
  }
  return assets;
}

function main() {
  const templates = readTemplates();
  const assets = readAssetsAsDataUris();

  const lines = [
    '// AUTO-GENERATED by packages/emails/scripts/generate-templates.mjs -- do not edit by hand.',
    '// Edit the source files under templates/ or assets/ and re-run that script instead.',
    '',
    'export const TEMPLATES: Record<string, Record<string, string>> = ' + JSON.stringify(templates, null, 2) + ';',
    '',
    'export const ASSET_DATA_URIS: Record<string, string> = ' + JSON.stringify(assets, null, 2) + ';',
    '',
  ];

  fs.writeFileSync(OUTPUT_PATH, lines.join('\n'));
  const templateCount = Object.values(templates).reduce((sum, byLocale) => sum + Object.keys(byLocale).length, 0);
  console.log(`Generated ${OUTPUT_PATH}`);
  console.log(`  ${Object.keys(templates).length} template(s), ${templateCount} locale file(s), ${Object.keys(assets).length} asset(s).`);
}

main();
