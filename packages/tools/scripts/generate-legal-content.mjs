#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseLegalMarkdown } from '../lib/legal-content.mjs';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '../../..');
const checkOnly = process.argv.includes('--check');

const definitions = [
  {
    id: 'terms',
    sourcePath: 'apps/docs/docs/legal/terms-of-service.md',
    sourceUrl: 'https://hashpass.club/documentation/legal/terms-of-service/',
  },
  {
    id: 'privacy',
    sourcePath: 'apps/docs/docs/legal/privacy-policy.md',
    sourceUrl: 'https://hashpass.club/documentation/legal/privacy-policy/',
  },
];

const documents = Object.fromEntries(
  definitions.map((definition) => {
    const markdown = fs.readFileSync(
      path.join(repositoryRoot, definition.sourcePath),
      'utf8',
    );
    return [definition.id, parseLegalMarkdown({ ...definition, markdown })];
  }),
);

const outputs = new Map();
const moduleSource = `// Generated by packages/tools/scripts/generate-legal-content.mjs.\n// Edit apps/docs/docs/legal/*.md, then run: pnpm legal:generate\n\nexport const GENERATED_LEGAL_DOCUMENTS = ${JSON.stringify(documents, null, 2)} as const;\n`;
outputs.set('apps/mobile-app/generated/legal-documents.ts', moduleSource);

for (const [id, document] of Object.entries(documents)) {
  outputs.set(
    `apps/docs/static/legal-content/${id}.json`,
    `${JSON.stringify(document, null, 2)}\n`,
  );
}

let stale = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(repositoryRoot, relativePath);
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;

  if (current === content) continue;
  stale = true;

  if (checkOnly) {
    console.error(`Stale generated legal content: ${relativePath}`);
    continue;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content);
  console.log(`Generated ${relativePath}`);
}

if (checkOnly && stale) {
  console.error('Run `pnpm legal:generate` and commit the generated files.');
  process.exitCode = 1;
} else if (checkOnly) {
  console.log('Generated legal content is current.');
}
