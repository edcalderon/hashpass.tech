import React from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { TextInput } from 'react-native';
import ContactMessages from '../../components/messages/ContactMessages';
import FloatingMessages from '../../components/messages/FloatingMessages';
import { ContactMessagingContext } from '../../contexts/ContactMessagingContext';
import type { MessagingContextValue } from '../../types/contact-messaging';
const mockPost = jest.fn();
jest.mock('../../lib/api-client', () => ({ apiClient: { post: (...args: unknown[]) => mockPost(...args) } }));
jest.mock('../../lib/vector-icons', () => ({ Ionicons: 'Icon' }));
jest.mock('../../i18n/i18n', () => ({ useTranslation: () => ({ t: (_key: string, fallback: string) => fallback }) }));
jest.mock('expo-crypto', () => ({ randomUUID: () => '00000000-0000-4000-8000-000000000003' }));
const peer = '00000000-0000-4000-8000-000000000002';
const person = { id: peer, name: 'Robin', avatar_url: 'https://example.test/robin.png', role: 'Builder', company: 'Studio', handle: 'robin', needs_reply: true, preview: 'Hello', updated_at: null };
const control = (view: ReactTestRenderer, label: string) => view.root.findAll(node => node.props.accessibilityLabel === label && typeof node.props.onPress === 'function').at(-1)!;
const input = (view: ReactTestRenderer, label: string) => view.root.findAllByType(TextInput).find(node => node.props.accessibilityLabel === label)!;
const context = (): MessagingContextValue => ({ account: 'account', error: null, loading: false, refreshVersion: 0, changed: jest.fn(), reload: jest.fn(), snapshot: { self: 'me', conversations: [person] } });
beforeEach(() => { jest.clearAllMocks(); mockPost.mockResolvedValue({ success: true, data: { data: { messages: [] } } }); });
it('hides the floating button once all conversations have been answered', () => {
  let view!: ReactTestRenderer;
  const onPress=jest.fn();
  act(() => { view=create(<FloatingMessages mode="light" conversations={[person]} onPress={onPress} />); });
  act(() => control(view,'Messages (1)').props.onPress()); expect(onPress).toHaveBeenCalled();
  act(() => view.update(<FloatingMessages mode="dark" conversations={[{...person,needs_reply:false}]} onPress={onPress} />));
  expect(view.toJSON()).toBeNull(); act(() => view.unmount());
});
it('opens a conversation without clearing pending replies and refreshes only after sending', async () => {
  const state=context(); let view!: ReactTestRenderer;
  await act(async () => { view=create(<ContactMessagingContext.Provider value={state}><ContactMessages mode="light" handle="my_handle" onContactAction={jest.fn()} onRefreshContacts={jest.fn()} /></ContactMessagingContext.Provider>); });
  await act(async () => control(view,'Reply: Robin').props.onPress());
  expect(mockPost).toHaveBeenCalledWith('contact-messages',{ action:'thread', peer },expect.anything());
  expect(state.changed).not.toHaveBeenCalled();
  act(() => input(view,'Message').props.onChangeText('Thanks, Robin!'));
  await act(async () => control(view,'Send message').props.onPress());
  expect(mockPost).toHaveBeenLastCalledWith('contact-messages',expect.objectContaining({action:'send',peer,body:'Thanks, Robin!'}),expect.anything());
  expect(state.changed).toHaveBeenCalled(); expect(input(view,'Message').props.value).toBe('');
  act(() => view.unmount());
});
it('retains the draft after a failed send and reuses its id on retry', async () => {
  const state=context(); let view!: ReactTestRenderer;
  await act(async () => { view=create(<ContactMessagingContext.Provider value={state}><ContactMessages mode="dark" peer={peer} handle="my_handle" onContactAction={jest.fn()} onRefreshContacts={jest.fn()} /></ContactMessagingContext.Provider>); });
  act(() => input(view,'Message').props.onChangeText('Retry this'));
  mockPost.mockRejectedValueOnce(new Error('offline'));
  await act(async () => control(view,'Send message').props.onPress());
  const original=mockPost.mock.calls.at(-1)[1];
  expect(input(view,'Message').props.value).toBe('Retry this'); expect(state.changed).not.toHaveBeenCalled();
  await act(async () => control(view,'Send message').props.onPress());
  expect(mockPost.mock.calls.at(-1)[1]).toEqual(original); expect(state.changed).toHaveBeenCalled();
  act(() => view.unmount());
});
it('submits only an exact handle and normalizes its @ prefix and case', async () => {
  const onAction=jest.fn(async () => true); let view!: ReactTestRenderer;
  await act(async () => { view=create(<ContactMessages mode="light" handle="my_handle" onContactAction={onAction} onRefreshContacts={jest.fn()} />); });
  expect(control(view,'Send contact request').props.accessibilityState.disabled).toBe(true);
  act(() => input(view,'Contact’s exact @handle').props.onChangeText(' @ROBIN '));
  await act(async () => control(view,'Send contact request').props.onPress());
  expect(onAction).toHaveBeenCalledWith({action:'request_handle',handle:'robin'});
  act(() => view.unmount());
});
