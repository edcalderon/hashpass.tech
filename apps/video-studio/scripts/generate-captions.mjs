#!/usr/bin/env node
// Merges each clip's per-clip SRT (from generate-narration.mjs's
// --write-subtitles output) into one caption-cue array per language, with
// timestamps shifted onto the *full composition's* timeline (chapter start
// + the same NARRATION_DELAY_FRAMES offset AppTutorialNarrated.tsx applies
// to the narration Audio track, so captions and voice line up exactly).
// Writes a plain TS data module the demo page imports directly — simpler
// and more robust than parsing VTT/SRT at runtime in the browser for
// something generated at build time anyway.
//
// Usage: pnpm --filter hashpass-video-studio captions:generate
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SUBS_DIR = join(ROOT, 'public/audio/subtitles');
const OUT_PATH = resolve(ROOT, '../mobile-app/lib/demo-captions.ts');

const FPS = 30;
const NARRATION_DELAY_SECONDS = 12 / FPS; // matches AppTutorialNarrated.tsx

// Chapter start times — mirrors apps/mobile-app/lib/demo-chapters.ts
// (kept in sync manually; both derive from the same recording durations).
const CHAPTERS = {
  en: [
    {slug: 'landing', startSeconds: 3},
    {slug: 'sign-up', startSeconds: 14.72},
    {slug: 'dashboard', startSeconds: 23.24},
    {slug: 'profile', startSeconds: 36.84},
    {slug: 'events', startSeconds: 45.72},
    {slug: 'pwa', startSeconds: 61.28},
  ],
  es: [
    {slug: 'landing', startSeconds: 3},
    {slug: 'sign-up', startSeconds: 17.24},
    {slug: 'dashboard', startSeconds: 26.2},
    {slug: 'profile', startSeconds: 39.76},
    {slug: 'events', startSeconds: 48.8},
    {slug: 'pwa', startSeconds: 65.12},
  ],
};

function parseSrtTimestamp(ts) {
  const [h, m, rest] = ts.split(':');
  const [s, ms] = rest.split(',');
  return Number(h) * 3600 + Number(m) * 60 + Number(s) + Number(ms) / 1000;
}

function parseSrt(content) {
  const blocks = content.trim().split(/\r?\n\r?\n/);
  const cues = [];
  for (const block of blocks) {
    const lines = block.split(/\r?\n/).filter(Boolean);
    if (lines.length < 2) continue;
    const timeLine = lines.find((l) => l.includes('-->'));
    if (!timeLine) continue;
    const [startRaw, endRaw] = timeLine.split('-->').map((s) => s.trim());
    const textLines = lines.slice(lines.indexOf(timeLine) + 1);
    cues.push({
      start: parseSrtTimestamp(startRaw),
      end: parseSrtTimestamp(endRaw),
      text: textLines.join(' ').trim(),
    });
  }
  return cues;
}

function main() {
  const result = {};

  for (const [lang, chapters] of Object.entries(CHAPTERS)) {
    const cues = [];

    for (const {slug, startSeconds} of chapters) {
      const srtPath = join(SUBS_DIR, lang, `${slug}.srt`);
      if (!existsSync(srtPath)) {
        console.warn(`Missing ${srtPath}, skipping`);
        continue;
      }
      const clipCues = parseSrt(readFileSync(srtPath, 'utf8'));
      const base = startSeconds + NARRATION_DELAY_SECONDS;

      for (const cue of clipCues) {
        cues.push({
          start: Math.round((base + cue.start) * 100) / 100,
          end: Math.round((base + cue.end) * 100) / 100,
          text: cue.text,
        });
      }
    }

    result[lang] = cues;
  }

  const fileContent = `// AUTO-GENERATED by apps/video-studio/scripts/generate-captions.mjs — do not
// edit by hand. Re-run that script after changing narration.json or
// re-timing any clip's trimStartSeconds.
export type DemoCaptionCue = {
  start: number;
  end: number;
  text: string;
};

export const demoCaptionsEn: DemoCaptionCue[] = ${JSON.stringify(result.en, null, 2)};

export const demoCaptionsEs: DemoCaptionCue[] = ${JSON.stringify(result.es, null, 2)};
`;

  writeFileSync(OUT_PATH, fileContent);
  console.log(`Wrote ${OUT_PATH}`);
  console.log(`EN cues: ${result.en.length}, ES cues: ${result.es.length}`);
}

main();
